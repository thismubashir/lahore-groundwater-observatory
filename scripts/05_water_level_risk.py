"""Stage 5: historical decline concern at monitored wells - where, what the data show, what could follow.

Run:  python scripts/05_water_level_risk.py
Needs: data/processed/ from stages 1-2 (no trained models).
Output: reports/water_level_risk.csv, .md (one row per well; kept local)
        reports/public_summary.json (aggregate counts only; used by the public dashboard)
"""

import _bootstrap  # noqa: F401
import pandas as pd

from lahore_gw import public_summary
from lahore_gw import water_risk as wr
from lahore_gw.config import PROCESSED_DIR, RAW_DIR, REPORTS_DIR
from lahore_gw.reporting import md_table


def main():
    long = pd.read_csv(PROCESSED_DIR / "lahore_groundwater_long.csv")
    wells = pd.read_csv(PROCESSED_DIR / "lahore_wells.csv")
    wpath = PROCESSED_DIR / "weather_seasonal_by_well.csv"
    weather = pd.read_csv(wpath) if wpath.exists() else None

    ind = wr.well_indicators(long, wells)
    rain = wr.rainfall_context(long, weather)
    summ = wr.network_summary(ind)
    latest = long.loc[long.season_index.idxmax()]
    latest_label = wr._label(latest.year, latest.season)

    ind = ind.assign(why=[" ".join(wr.explain_why(r, rain)) for _, r in ind.iterrows()],
                     future_risks=[" ".join(wr.future_risks(r, latest_label)) for _, r in ind.iterrows()])
    ind.to_csv(REPORTS_DIR / "water_level_risk.csv", index=False)
    write_report(ind, rain, summ, latest_label)
    disc_path = REPORTS_DIR / "audit" / "coordinate_discrepancies.csv"
    disc = pd.read_csv(disc_path) if disc_path.exists() else pd.DataFrame(columns=["gis_no", "distance_km"])
    public_summary.write(public_summary.build(long, wells, weather, disc, RAW_DIR),
                         REPORTS_DIR / "public_summary.json")
    c = summ["counts"]
    print(f"concern: High {c['High']}, Medium {c['Medium']}, {wr.NO_DECLINE} {c[wr.NO_DECLINE]}, "
          f"Unknown {c['Unknown']}; {summ['deeper_than_25ft']} wells deeper than 25 ft at last reading")


def write_report(ind, rain, summ, latest_label):
    c = summ["counts"]
    rules = "\n".join(f"* **{k}**: {v}" for k, v in wr.CONCERN_RULES.items())
    table = ind.assign(trend_ft_per_year=ind.trend_ft_per_year.round(2),
                       last_depth_ft=ind.last_depth_ft.round(1),
                       projected_depth_ft=ind.projected_depth_ft.round(0))
    cols = ["well_id", "village", "tehsil", "concern", "trend_ft_per_year", "last_reading", "last_depth_ft",
            "deeper_than_25ft", "projected_depth_ft"]
    sections = []
    for _, r in ind[ind.concern.isin(["High", "Medium"])].iterrows():
        why = "\n".join(f"* {s}" for s in wr.explain_why(r, rain))
        risks = "\n".join(f"* {s}" for s in wr.future_risks(r, latest_label))
        sections.append(f"### {r.well_id} - {r.village} ({r.tehsil}): {r.concern} concern\n\n"
                        f"**What the readings show:**\n\n{why}\n\n**Possible future problems:**\n\n{risks}\n")
    text = f"""# {wr.CONCERN_TITLE}: where, what the data show, and what could follow

Generated by `scripts/05_water_level_risk.py` from the observed readings (latest survey: {latest_label}).
No forecast model is used here. **These are historical data (to 2020), not current conditions.**

## Where

{summ['deepening']} of {summ['with_trend']} wells with enough readings were deepening, and {summ['rising']} were rising.
The median trend was {summ['median_trend_ft_per_year']:+.2f} ft/year (positive = deeper).
{summ['deeper_than_25ft']} of {summ['wells']} wells were deeper than ~{wr.SUCTION_LIMIT_FT:.0f} ft at their last reading,
beyond the typical lift of surface-mounted suction pumps (an indicator only; it does not apply to
submersible or other deep-well pumps).

{wr.CONCERN_TITLE}: **High {c['High']}**, Medium {c['Medium']}, {wr.NO_DECLINE} {c[wr.NO_DECLINE]},
Unknown {c['Unknown']}. These describe 2003-2020 readings at monitored wells only, not current conditions
or the whole city.

{rules}

Trend = Theil-Sen slope of pre-monsoon depths (one reading per year, so the monsoon cycle does not bias it).

{md_table(table, cols, digits=2)}

## What the data can say about causes

{wr.rainfall_text(rain)}

{wr.DRIVERS_NOT_MEASURED}

## High and medium concern wells

{chr(10).join(sections)}
## Limits

* {wr.HORIZON_YEAR} values extend each well's historical trend in a straight line. They are scenarios, not validated forecasts.
* Several wells stopped being read years ago (see "Monitoring gap"); their present state is unknown.
* About 30 monitoring points cannot describe every neighbourhood of Lahore.
"""
    (REPORTS_DIR / "water_level_risk.md").write_text(text)


if __name__ == "__main__":
    main()
