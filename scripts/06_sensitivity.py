"""Stage 6: sensitivity of the held-out results to the timing and metadata assumptions.

Run:  python scripts/06_sensitivity.py            (about 5 minutes)
Needs: data/processed/ and models/training_info.json from stages 1-3.
Output: reports/sensitivity.csv, reports/sensitivity.md

The published configuration (31 May / 31 Oct windows, all features) was fixed
before these checks. The variants below are a fixed list, all reported. They
are NOT used to choose the model, and the best-scoring variant is not adopted.
For each variant the ridge alpha is re-chosen on validation rows only. The
network reuses the published epoch count. Every model is refitted on
train+validation and scored once on the test rows.
"""

import json

import _bootstrap  # noqa: F401
import numpy as np
import pandas as pd

from lahore_gw.config import MODELS_DIR, PROCESSED_DIR, REPORTS_DIR
from lahore_gw.features import FEATURES, WEATHER_FEATURES, build_samples, chronological_split
from lahore_gw.modeling import NNEnsemble, RidgeChange, bootstrap_mae_diff, metrics, persistence
from lahore_gw.reporting import md_table
from lahore_gw.weather import build_weather_table

TRAIN_LAST_YEAR, VAL_LAST_YEAR = 2012, 2015          # same split as stage 3
RIDGE_ALPHAS = [0.1, 1, 3, 10, 30, 100, 300]


def evaluate(S, feats, label, group, n_epochs):
    tr, va, te = chronological_split(S, TRAIN_LAST_YEAR, VAL_LAST_YEAR)
    alpha = min(RIDGE_ALPHAS, key=lambda a: metrics(va.target_depth_ft,
                                                     RidgeChange(a, feats).fit(tr).predict(va))["mae_ft"])
    trval = pd.concat([tr, va])
    ridge = RidgeChange(alpha, feats).fit(trval).predict(te)
    nn = NNEnsemble(n_members=5, features=feats).fit(trval, epochs=n_epochs).predict(te)
    y = te.target_depth_ft
    d, lo, hi = bootstrap_mae_diff(y, ridge, persistence(te), groups=te.well_id.to_numpy())
    return {"group": group, "variant": label, "test_rows": len(te), "test_wells": te.well_id.nunique(),
            "ridge_alpha": alpha, "ridge_mae_ft": metrics(y, ridge)["mae_ft"],
            "nn_mae_ft": metrics(y, nn)["mae_ft"], "persistence_mae_ft": metrics(y, persistence(te))["mae_ft"],
            "ridge_minus_persistence_ft": d, "ci95_low": lo, "ci95_high": hi}


def main():
    long = pd.read_csv(PROCESSED_DIR / "lahore_groundwater_long.csv")
    wells = pd.read_csv(PROCESSED_DIR / "lahore_wells.csv")
    weather = pd.read_csv(PROCESSED_DIR / "weather_seasonal_by_well.csv")
    epochs = json.loads((MODELS_DIR / "training_info.json").read_text())["nn_final_epochs"]
    years = range(int(long.year.min()) - 1, int(long.year.max()) + 1)
    S = build_samples(long, wells, weather)
    rows = [evaluate(S, FEATURES, "As published (windows end 31 May / 31 Oct)", "reference", epochs)]
    for days in (31, 61):
        shifted, _ = build_weather_table(wells, years, shift_days=days)
        rows.append(evaluate(build_samples(long, wells, shifted), FEATURES,
                             f"Weather windows end {days} days earlier", "timing", epochs))
    rows.append(evaluate(S, [f for f in FEATURES if f not in ("rain_t_mm", "t2m_t_c")],
                         "Without weather of the window ending at the reading", "timing", epochs))
    rows.append(evaluate(S, [f for f in FEATURES if f not in WEATHER_FEATURES], "Without any weather",
                         "timing", epochs))
    rows.append(evaluate(S, [f for f in FEATURES if f not in ("lat", "lon", "ground_elevation_m")],
                         "Without latitude, longitude and elevation", "metadata", epochs))
    flagged = wells.loc[wells.coord_quality != "consistent", "well_id"]
    rows.append(evaluate(S[~S.well_id.isin(flagged)], FEATURES,
                         f"Excluding the {len(flagged)} coordinate-flagged wells", "metadata", epochs))
    res = pd.DataFrame(rows)
    res.to_csv(REPORTS_DIR / "sensitivity.csv", index=False)
    write_report(res, epochs)
    print(res[["variant", "ridge_mae_ft", "nn_mae_ft", "ridge_minus_persistence_ft", "ci95_low", "ci95_high"]]
          .round(3).to_string(index=False))


def write_report(res, epochs):
    clear = bool((res.ci95_high < 0).all())
    show = res[["group", "variant", "test_rows", "ridge_alpha", "ridge_mae_ft", "nn_mae_ft", "persistence_mae_ft",
                "ridge_minus_persistence_ft", "ci95_low", "ci95_high"]]
    text = f"""# Sensitivity of held-out results (generated by `scripts/06_sensitivity.py`)

The published configuration was fixed before these checks. Every variant in this fixed list is
reported, and none is used to choose the model. For each variant the ridge alpha is re-chosen on
validation rows only. The network reuses the published epoch count ({epochs}). All models are
refitted on train+validation and scored once on the test rows.

* **Timing.** The workbooks have no measurement dates, so the 31 May / 31 Oct window ends are
  assumptions. Ending every window earlier, or dropping weather of the window that ends at the
  reading, tests whether weather from after an actual survey date could have helped the models.
* **Metadata.** Some coordinates disagree between files, and two elevations are unresolved. These
  variants remove the location inputs or the flagged wells. The excluded-wells variant has fewer
  test rows, so compare it with its own persistence MAE.

{md_table(show, digits=3)}

`ridge_minus_persistence_ft` is the MAE difference (negative = ridge better), with a 95% interval
from a bootstrap that resamples whole wells. Ridge is {'clearly better than persistence in every variant' if clear
else 'NOT clearly better than persistence in at least one variant'}.
"""
    (REPORTS_DIR / "sensitivity.md").write_text(text)


if __name__ == "__main__":
    main()
