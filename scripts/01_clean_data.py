"""Stage 1: read original workbooks (+ 2019 PDF), clean, and write the audit.

Run:  python scripts/01_clean_data.py
Outputs kept local (git-ignored; per-well data, see docs/DATA_POLICY.md):
  data/processed/lahore_wells.csv, data/processed/lahore_groundwater_long.csv
  reports/audit/*.csv, reports/audit/data_audit_full.md (per-well coordinates and coverage)
  reports/figures/coverage_heatmap.png, reports/figures/example_well_trends.png
Outputs that can be published after review (aggregates only):
  reports/data_audit.md, reports/figures/median_depth_by_season.png
"""

import argparse
import hashlib
import warnings

import _bootstrap  # noqa: F401

from lahore_gw.cleaning import clean, save
from lahore_gw.config import FIGURES_DIR, RAW_DIR, REPORTS_DIR
from lahore_gw import plots
from lahore_gw.reporting import md_table

warnings.filterwarnings("ignore", message="Cannot parse header or footer")


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main(include_pdf=True):
    raw_files = sorted(p for p in RAW_DIR.iterdir() if p.is_file() and not p.name.startswith("."))
    before = {p.name: sha256(p) for p in raw_files}

    res = clean(include_pdf=include_pdf)
    by_season, by_well = save(res)

    after = {p.name: sha256(p) for p in raw_files}
    assert before == after, "Raw files changed during cleaning!"

    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    plots.coverage_heatmap(res.long, FIGURES_DIR / "coverage_heatmap.png")
    plots.median_depth_by_season(res.long, FIGURES_DIR / "median_depth_by_season.png")
    plots.well_trends(res.long, ["LHR-108", "LHR-155", "LHR-148"], FIGURES_DIR / "example_well_trends.png",
                      "Depth to water: three long-record wells")

    L = res.long
    n_read = int((L.status == "reading").sum())
    pd = __import__("pandas")
    lines = [
        "# Data audit: Lahore District piezometer readings\n",
        "Generated by `scripts/01_clean_data.py`. All numbers come from the original files; "
        "nothing was imputed into the clean dataset.\n",
        "## Source files (unchanged, SHA-256 verified before and after cleaning)\n",
        md_table(pd.DataFrame([{"file": k, "sha256": v[:16] + "…"} for k, v in before.items()])),
        "\n## Scope\n",
        f"* Monitoring locations kept (District = Lahore): **{len(res.wells)}**. "
        "Rows from other districts of the Lahore Irrigation Zone (Sialkot, Kasur, Okara, …) were dropped.",
        f"* Seasons covered by at least one file: **{L.season_index.nunique()}** "
        f"({L.year.min()}–{L.year.max()}).",
        f"* Well-season cells in the grid: **{len(L)}**; real readings: **{n_read}** "
        f"({n_read / len(L):.0%}).",
        f"* Status counts: {L.status.value_counts().to_dict()}.",
        "* `closed`, `dead`, `blank` = no reading; `not_listed` = the well is absent from that file.",
        f"* Wells usable for modelling (≥4 readings and ≥2 consecutive-season pairs): "
        f"**{int(by_well.usable_for_modeling.sum())}**.",
        "\n## Notes\n",
        *[f"* {n}" for n in res.notes],
        "\n## Identifier verification\n",
        "Every GIS number maps to exactly one DLR number in every file (and vice versa), "
        "so `well_id = LHR-<GIS no.>` is a verified identifier. Village-name spelling variants:\n",
        md_table(res.identifier_checks[res.identifier_checks.village_variants.str.contains(";")],
                 ["gis_no", "dlr_values", "village_variants"]),
        "\n## Overlapping / conflicting records\n",
        md_table(res.conflicts, ["gis_no", "year", "season", "conflict_type", "raw_values"])
        if len(res.conflicts) else "No disagreements: all overlapping records carry identical values.\n",
        "\n## Coordinate discrepancies between files (> 50 m)\n",
        md_table(res.coord_discrepancies),
        "\nThe most recent file's coordinates are used; nothing is averaged or corrected by hand. "
        "See `coord_quality` in the wells table for plain-language flags.\n",
        "\n## Coverage by season\n",
        md_table(by_season.drop(columns="season_index")),
        "\n## Coverage by well\n",
        md_table(by_well.drop(columns=["max_coord_discrepancy_km"])),
        "\n![coverage](figures/coverage_heatmap.png)\n",
    ]
    (REPORTS_DIR / "audit" / "data_audit_full.md").write_text(
        "\n".join(lines).replace("figures/coverage_heatmap.png", "../figures/coverage_heatmap.png"))
    (REPORTS_DIR / "data_audit.md").write_text(public_audit(res, before, by_season, by_well, n_read))
    print(f"wells={len(res.wells)} readings={n_read} conflicts={len(res.conflicts)} "
          f"usable={int(by_well.usable_for_modeling.sum())}")
    for n in res.notes:
        print(" -", n)


def public_audit(res, hashes, by_season, by_well, n_read) -> str:
    """Aggregate-only audit for publication: no coordinates, readings or per-well rows."""
    import pandas as pd
    L, W, disc = res.long, res.wells, res.coord_discrepancies
    unresolved = W[W.elevation_status.str.startswith("unresolved")]
    notes = [n for n in res.notes if not n.startswith("Ground elevation differs")]
    lines = [
        "# Data audit (aggregate summary)\n",
        "Generated by `scripts/01_clean_data.py`. This public summary contains counts only. The full audit "
        "with per-well coordinates and coverage is written locally to `reports/audit/data_audit_full.md`, "
        "because the source workbooks' redistribution terms are unverified.\n",
        "## Source files (unchanged, SHA-256 verified before and after cleaning)\n",
        md_table(pd.DataFrame([{"file": k, "sha256": v[:16] + "…"} for k, v in hashes.items()])),
        "\n## Scope\n",
        f"* Monitoring locations kept (District = Lahore): **{len(W)}** in {W.tehsil.nunique()} tehsils.",
        f"* Seasons covered: **{L.season_index.nunique()}** ({L.year.min()}–{L.year.max()}); "
        f"well-season cells: **{len(L)}**; real readings: **{n_read}** ({n_read / len(L):.0%}).",
        f"* Status counts: {L.status.value_counts().to_dict()}. `closed`, `dead`, `blank` = no reading; "
        "`not_listed` = absent from that file. None is treated as zero.",
        f"* Wells usable for modelling (≥4 readings and ≥2 consecutive-season pairs): "
        f"**{int(by_well.usable_for_modeling.sum())}**.",
        f"* GIS↔DLR identifiers one-to-one in every file: **{bool(res.identifier_checks.gis_dlr_consistent.all())}**.",
        "\n## Notes\n",
        *[f"* {n}" for n in notes],
        f"* Ground elevation: files disagree for **{len(unresolved)} wells** "
        f"({', '.join(unresolved.well_id)}); left unresolved and not used by the models.",
        f"* Coordinates differ between files for **{len(disc)} wells** (largest difference "
        f"{disc.distance_km.max():.1f} km); {int((disc.distance_km > 1).sum())} differ by more than 1 km. "
        f"**{int((W.coord_quality != 'consistent').sum())} wells** carry a coordinate flag in total.",
        "\n## Coverage by season (counts across all wells)\n",
        md_table(by_season.drop(columns="season_index")),
        "\n![median depth](figures/median_depth_by_season.png)\n",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-pdf", action="store_true", help="skip the 2019 PDF")
    main(include_pdf=not ap.parse_args().no_pdf)
